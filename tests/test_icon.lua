local texture=assert(toc:match("## IconTexture: ([^\r\n]+)"))
local path=texture:gsub("\\","/"):gsub("^Interface/AddOns/Foreverbuddyui/", "")
assert(path=="Media/BuddyIcon.tga", "addon list icon must use an explicit game texture")
local file=assert(io.open(path,"rb"));local data=file:read("*a");file:close()
